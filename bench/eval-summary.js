#!/usr/bin/env node
// Model comparison table, rebuilt from the eval reports on disk.
//
// `bench/evals.js` already writes one JSON report per run into
// bench/runs/evals/. This turns the latest report per model into a single
// ranked table, so a bake-off survives the session that ran it — the first one
// was tracked in a scratchpad TSV and was gone by the next session, while the
// reports it was derived from sat here untouched the whole time.
//
// node bench/eval-summary.js            # print
// node bench/eval-summary.js --write    # write bench/BAKEOFF.md
// node bench/eval-summary.js --since 2026-08-11
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPORTS_DIR = path.join(__dirname, 'runs', 'evals');
const OUTPUT_FILE = path.join(__dirname, 'BAKEOFF.md');

async function main() {
  const argv = process.argv.slice(2);
  const args = new Set(argv);
  const sinceIdx = argv.indexOf('--since');
  const since = sinceIdx === -1 ? null : argv[sinceIdx + 1];

  const runs = await loadLatestPerModel(since);
  if (!runs.length) throw new Error(`No eval reports in ${path.relative(process.cwd(), REPORTS_DIR)}`);
  const markdown = renderMarkdown(runs, since);

  if (args.has('--write')) {
    await fs.writeFile(OUTPUT_FILE, markdown, 'utf8');
    console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)} (${runs.length} models)`);
    return;
  }
  process.stdout.write(markdown);
}

/**
 * Latest result per (model, case), not per model. A bake-off is run in pieces —
 * a new case added, one model re-run after a fix — and keeping only each model's
 * newest *report* silently drops every case that run did not include, which
 * reads as "never tested" for results that are sitting right there on disk.
 */
async function loadLatestPerModel(since) {
  const entries = await fs.readdir(REPORTS_DIR);
  const latest = new Map(); // model -> caseId -> {stamp, result}

  for (const entry of entries) {
    if (!entry.endsWith('.json')) continue;
    if (since && entry < since) continue;
    let report;
    try {
      report = JSON.parse(await fs.readFile(path.join(REPORTS_DIR, entry), 'utf8'));
    } catch {
      continue; // a run killed mid-write should not break the table
    }
    if (!report?.model || !Array.isArray(report.results)) continue;
    const stamp = report.generatedAt ?? entry;
    if (!latest.has(report.model)) latest.set(report.model, new Map());
    const byCase = latest.get(report.model);
    for (const result of report.results) {
      const prev = byCase.get(result.caseId);
      if (!prev || stamp > prev.stamp) byCase.set(result.caseId, { stamp, result });
    }
  }

  return [...latest.entries()]
    .map(([model, byCase]) => {
      const results = [...byCase.values()].map(v => v.result);
      const sum = (fn) => results.reduce((a, r) => a + fn(r), 0);
      return {
        model,
        cases: results.length,
        passed: results.filter(r => r.passAtK).length,
        // Per-case durations, so a merged row still adds up to real wall clock.
        seconds: Math.round(sum(r => (r.iterations ?? []).reduce((a, it) => a + (it.durationMs ?? 0), 0)) / 1000),
        promptTokens: sum(r => (r.avgPromptTokens ?? 0) * (r.repeat ?? 1)),
        completionTokens: sum(r => (r.avgCompletionTokens ?? 0) * (r.repeat ?? 1)),
        failed: results.filter(r => !r.passAtK).map(r => r.caseId).sort(),
        perCase: new Map(results.map(r => [r.caseId, r.passAtK])),
      };
    })
    // Correctness first, then coverage, then wall clock. Coverage has to outrank
    // time or a clean 5-case run sorts above a clean 9-case one that includes
    // the hard cases; on this machine the remaining gap is entirely speed.
    .sort((a, b) =>
      rate(b) - rate(a) || b.cases - a.cases || a.seconds - b.seconds || a.model.localeCompare(b.model));
}

const rate = (run) => (run.cases ? run.passed / run.cases : 0);

function renderMarkdown(runs, since) {
  const caseIds = [...new Set(runs.flatMap(r => [...r.perCase.keys()]))].sort();
  const lines = [
    '# Eval bake-off',
    '',
    '<!-- Generated by `node bench/eval-summary.js --write` — do not edit by hand. -->',
    '',
    `Latest result per model and case${since ? ` (reports since \`${since}\`)` : ''}, ranked by pass rate then wall clock.`,
    'Models did not all run the same cases — check the coverage table before comparing two rows.',
    '',
    '| Model | Score | Sec | In | Out | Failed |',
    '|---|---|---|---|---|---|',
  ];

  for (const run of runs) {
    lines.push(`| \`${run.model}\` | ${run.passed}/${run.cases} | ${run.seconds} | ` +
      `${run.promptTokens.toLocaleString()} | ${run.completionTokens.toLocaleString()} | ` +
      `${run.failed.length ? run.failed.join(', ') : '—'} |`);
  }

  lines.push('', '## Coverage', '',
    `| Model | ${caseIds.join(' | ')} |`,
    `|---|${caseIds.map(() => '---').join('|')}|`);
  for (const run of runs) {
    const cells = caseIds.map(id => {
      if (!run.perCase.has(id)) return '·';
      return run.perCase.get(id) ? '✓' : '✗';
    });
    lines.push(`| \`${run.model}\` | ${cells.join(' | ')} |`);
  }
  lines.push('', '`·` = the model never ran that case.', '');

  return lines.join('\n');
}

main().catch(error => {
  console.error(error.message);
  process.exit(1);
});
